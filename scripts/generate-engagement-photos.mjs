// Generates web gallery copies of the engagement photos.
// Input: a folder of already web-optimized JPEGs (EXIF stripped), default /workspace/engagement-photos/web
// Output: public/images/engagement/{thumbs,full}/ and app/photos/engagement-photos.ts
// Usage: node scripts/generate-engagement-photos.mjs [sourceDir]
import sharp from 'sharp';
import fs from 'node:fs';
import path from 'node:path';

const src = process.argv[2] || '/workspace/engagement-photos/web';
const out = 'public/images/engagement';
const THUMB = 720;
const FULL = 1600;

fs.mkdirSync(`${out}/thumbs`, { recursive: true });
fs.mkdirSync(`${out}/full`, { recursive: true });

const files = fs.readdirSync(src).filter((f) => /\.jpe?g$/i.test(f)).sort();
const list = [];
let thumbBytes = 0;
let fullBytes = 0;

for (const f of files) {
  const name = path.parse(f).name;
  const input = path.join(src, f);
  const thumb = await sharp(input)
    .rotate()
    .resize({ width: THUMB, height: THUMB, fit: 'inside', withoutEnlargement: true })
    .jpeg({ quality: 76, mozjpeg: true, progressive: true })
    .toBuffer({ resolveWithObject: true });
  const full = await sharp(input)
    .rotate()
    .resize({ width: FULL, height: FULL, fit: 'inside', withoutEnlargement: true })
    .jpeg({ quality: 80, mozjpeg: true, progressive: true })
    .toBuffer({ resolveWithObject: true });
  fs.writeFileSync(`${out}/thumbs/${name}.jpg`, thumb.data);
  fs.writeFileSync(`${out}/full/${name}.jpg`, full.data);
  thumbBytes += thumb.data.length;
  fullBytes += full.data.length;
  list.push({ name, w: full.info.width, h: full.info.height });
}

const ts = `// Generated by scripts/generate-engagement-photos.mjs. Do not edit by hand.
export type EngagementPhoto = { name: string; w: number; h: number };

export const ENGAGEMENT_PHOTOS: EngagementPhoto[] = [
${list.map((p) => `  { name: "${p.name}", w: ${p.w}, h: ${p.h} },`).join('\n')}
];
`;
fs.writeFileSync('app/photos/engagement-photos.ts', ts);
console.log(JSON.stringify({ count: list.length, thumbBytes, fullBytes }));
